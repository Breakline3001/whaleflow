import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const executable=path.join(root,'release','win-unpacked','WhaleFlow.exe');
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;
const child=spawn(executable,process.argv.slice(2),{cwd:root,env,stdio:'inherit'});
child.on('error',error=>{console.error(error);process.exitCode=1;});
child.on('exit',code=>{console.log(`[packaged-runner] exit=${code}`);process.exitCode=code??1;});
process.on('SIGINT',()=>child.kill());process.on('SIGTERM',()=>child.kill());
